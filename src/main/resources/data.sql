-- ====================
-- 1. TẠO CẤU TRÚC BẢNG
-- ====================

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    username VARCHAR(50) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(255),
    phone_number VARCHAR(20) UNIQUE NOT NULL,
    role VARCHAR(20),
    email VARCHAR(50),
    address VARCHAR(255),
    gender VARCHAR(20),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);;

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT DEFAULT 0,
    account_number VARCHAR(20) UNIQUE NOT NULL,
    account_type VARCHAR(50) DEFAULT 'PAYMENT',
    transaction_limit VARCHAR(50) DEFAULT '50M',
    interest_rate DECIMAL(5, 2),
    term_months INT,
    balance DECIMAL(19, 2) DEFAULT 0,
    date_open TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    -- "Rào chắn an toàn" cuối cùng: DB sẽ từ chối lưu nếu balance bị âm,
    -- kể cả khi code Java có lỗi logic. Vi phạm sẽ ném lỗi và kích hoạt Rollback ở tầng Service.
    CONSTRAINT chk_accounts_balance_non_negative CHECK (balance >= 0)
);;

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(50), 
    type VARCHAR(50),
    direction VARCHAR(20),
    amount DECIMAL(19, 2),
    description VARCHAR(255),
    transaction_date TIMESTAMP,
    account_id BIGINT,
    related_account_number VARCHAR(20),
    CONSTRAINT fk_account FOREIGN KEY (account_id) REFERENCES accounts(id),
    CONSTRAINT uk_txn_direction UNIQUE (transaction_id, direction)
);;

CREATE TABLE IF NOT EXISTS user_update_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    new_full_name VARCHAR(255),
    new_phone_number VARCHAR(20),
    new_email VARCHAR(50),
    new_address VARCHAR(255),
    new_gender VARCHAR(20),
    status VARCHAR(20) DEFAULT 'PENDING',
    request_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    detail VARCHAR(500),
    CONSTRAINT fk_request_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);;

